import { spawnSync } from 'node:child_process';
import { existsSync } from 'node:fs';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { dirname } from 'node:path';
const model = JSON.parse(await readFile('contracts/model.json', 'utf8'));
const check = process.argv.includes('--check');
let changed = false;
async function output(path, value) {
  let text = value.trimEnd() + '\n';
  if (path.endsWith('.go')) {
    const f = spawnSync(
      existsSync('tools/.cache/go/bin/gofmt.exe') ? 'tools/.cache/go/bin/gofmt.exe' : 'gofmt',
      [],
      { input: text, encoding: 'utf8' }
    );
    if (f.status !== 0) throw Error('gofmt unavailable');
    text = f.stdout;
  }
  if (check) {
    if ((await readFile(path, 'utf8').catch(() => '')) !== text) {
      console.error(`Contract drift: ${path}`);
      changed = true;
    }
  } else {
    await mkdir(dirname(path), { recursive: true });
    await writeFile(path, text);
  }
}
const goType = {
  int: 'int',
  int64: 'int64',
  float64: 'float64',
  string: 'string',
  time: 'time.Time',
};
const tsType = {
  int: 'number',
  int64: 'number',
  float64: 'number',
  string: 'string',
  time: 'string',
};
let go =
  '// Code generated by tools/codegen/contracts.mjs; DO NOT EDIT.\npackage contract\n\nimport "time"\n\n';
let ts = '// Generated from contracts/model.json. DO NOT EDIT.\n';
for (const [name, fields] of Object.entries(model.types)) {
  go += `type ${name} struct {\n`;
  ts += `export interface ${name} {\n`;
  const properties = {};
  for (const [key, type] of Object.entries(fields)) {
    const field = key[0].toUpperCase() + key.slice(1);
    go += `\t${field} ${goType[type] || type} \`json:"${key}"\`\n`;
    ts += `  ${key}: ${tsType[type] || type};\n`;
    properties[key] =
      type === 'Message'
        ? { $ref: 'message.json' }
        : {
            type:
              type === 'string' || type === 'time'
                ? 'string'
                : type === 'float64'
                  ? 'number'
                  : 'integer',
            ...(type === 'time' ? { format: 'date-time' } : {}),
          };
  }
  go += '}\n\n';
  ts += '}\n';
  if (name === 'Message') {
    properties.schemaVersion = { const: 1 };
    for (const key of ['deviceId', 'tenantId', 'projectId', 'bootId', 'messageId'])
      properties[key].pattern = '^[A-Za-z0-9_-]{1,80}$';
    properties.sequence.minimum = 0;
    properties.kind.enum = [
      'BIRTH',
      'LWT',
      'HEARTBEAT',
      'SNAPSHOT',
      'LIVE',
      'ALARM',
      'EVENT',
      'WATCH_START',
      'WATCH_RENEW',
      'WATCH_STOP',
      'WATCH_ACK',
    ];
  }
  await output(
    `contracts/schemas/v1/${name.toLowerCase()}.json`,
    JSON.stringify(
      {
        $schema: 'https://json-schema.org/draft/2020-12/schema',
        $id: `https://contracts.invalid/crane/v1/${name.toLowerCase()}.json`,
        type: 'object',
        additionalProperties: false,
        required: Object.keys(fields),
        properties,
      },
      null,
      2
    )
  );
}
await output('contracts/go/types.gen.go', go);
await output('contracts/typescript/types.gen.ts', ts);
await output(
  'contracts/go/topics.gen.go',
  `// Code generated by tools/codegen/contracts.mjs; DO NOT EDIT.
package contract

var Topics = map[string]byte{
${Object.entries(model.topics)
  .map(([t, v]) => `\t"${t}": ${v.qos},`)
  .join('\n')}
}
`
);
const channels = Object.fromEntries(
  Object.entries(model.topics).map(([topic, meta], i) => [
    'channel' + i,
    {
      address: model.namespace + '/{tenantId}/{projectId}/{deviceId}/' + topic,
      parameters: { tenantId: {}, projectId: {}, deviceId: {} },
      messages: { message: { $ref: '#/components/messages/Message' } },
      'x-direction': meta.direction,
    },
  ])
);
await output(
  'contracts/asyncapi/edge-mqtt.yaml',
  JSON.stringify(
    {
      asyncapi: '3.0.0',
      info: { title: 'Crane Edge MQTT', version: '1.0.0' },
      servers: {
        dev: {
          host: 'mosquitto:8883',
          protocol: 'mqtts',
          protocolVersion: '5',
          security: [{ deviceCertificate: [] }],
        },
      },
      channels,
      operations: Object.fromEntries(
        Object.entries(channels).map(([k, v]) => [
          k,
          {
            action: v['x-direction'] === 'edge-to-cloud' ? 'receive' : 'send',
            channel: { $ref: '#/channels/' + k },
            bindings: {
              mqtt: {
                qos: model.topics[v.address.split('{deviceId}/')[1]].qos,
                bindingVersion: '0.2.0',
              },
            },
          },
        ])
      ),
      components: {
        messages: { Message: { payload: { $ref: '../schemas/v1/message.json' } } },
        securitySchemes: { deviceCertificate: { type: 'X509' } },
      },
    },
    null,
    2
  )
);
if (changed) process.exitCode = 1;
